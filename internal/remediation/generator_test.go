func TestGenerateManifest_K8sTargetFallback(t *testing.T) {
	tmpDir := t.TempDir()
	cfg := &config.RemediationConfig{
		AutoGenerate: true,
		OutputDir:    tmpDir,
	}

	gen := NewGenerator(cfg)
	decision := &policy.DecisionResult{
		Decision: "block",
		FlagKey:  "test-flag",
		Reasons:  []string{"some-service stale chaos"},
		BlastRadius: []aggregator.AggregatedServiceSignal{
			{Service: "some-service", Confidence: 0.75},
		},
	}

	// Empty catalog — should use auto-generated K8s target info
	path, err := gen.GenerateManifest(context.Background(), decision, nil)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	if path == "" {
		t.Fatal("expected non-empty path")
	}

	data, _ := os.ReadFile(filepath.Join(tmpDir, "some-service-pod-delete-min.yaml"))
	var manifest ExperimentManifest
	_ = yaml.Unmarshal(data, &manifest)

	// Fallback should auto-derive namespace from service name
	if !strings.Contains(manifest.Experiment.Target.LabelSelector, "some-service") {
		t.Errorf("expected auto-derived label selector containing some-service, got %s", manifest.Experiment.Target.LabelSelector)
	}
}

func TestGenerateManifest_SetsRemediationOnDecision(t *testing.T) {
	tmpDir := t.TempDir()
	cfg := &config.RemediationConfig{
		AutoGenerate: true,
		OutputDir:    tmpDir,
	}

	gen := NewGenerator(cfg)
	decision := &policy.DecisionResult{
		Decision: "block",
		FlagKey:  "test-flag",
		Reasons:  []string{"target-service stale"},
		BlastRadius: []aggregator.AggregatedServiceSignal{
			{Service: "target-service", Confidence: 0.9},
		},
	}

	_, _ = gen.GenerateManifest(context.Background(), decision, nil)

	if decision.SuggestedRemediation == "" {
		t.Error("expected SuggestedRemediation to be set on the decision result after generation")
	}
}
